export const findLanguage = (code) => {
  if (!code) return DEFAULT_LANGUAGE;
  const match = INDIAN_LANGUAGES.find(
    (l) => l.code.toLowerCase() === code.toLowerCase() || code.toLowerCase().startsWith(l.code.toLowerCase())
  );
  return match || DEFAULT_LANGUAGE;
};
